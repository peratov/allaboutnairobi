"""
The constituency outlines Nairobi Pulse's function checks a location against.

    python scripts/build_pulse_districts.py

Nairobi Pulse counts a vote only from inside Nairobi City County, and counts it
in the constituency the voter's phone was in. The function decides that by
testing the point against the same 17 constituency shapes /map draws - but a
serverless function only ships what its file tracer sees imported, so it
cannot read templates/geo/nairobi-map.json at run time. This writes the shapes
into api/_pulse/districts.mjs, as a module, with the projection that turns a
latitude and longitude into the same map units.

The Pulse code calls them "districts" throughout (it came from All About
Accra, where they are district assemblies); in Nairobi each is a constituency.

Run it after scripts/build_nairobi_map.py. scripts/check_pulse.mjs fails if
the two have drifted.

The map's projection (scripts/build_nairobi_map.py) is

    x = (lon - LON0) * unitsPerDegLon
    y = -(lat - LAT0) * unitsPerDegLat

and api/_pulse/geo.mjs computes

    x = (lon - west) * cosLat * scale
    y = height - (lat - south) * scale

so west = LON0, south = LAT0, scale = unitsPerDegLat, height = 0 and
cosLat = unitsPerDegLon / unitsPerDegLat.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "templates" / "geo" / "nairobi-map.json"
TARGET = ROOT / "api" / "_pulse" / "districts.mjs"

NUMBER = re.compile(r"-?\d+(?:\.\d+)?")


def main() -> int:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    meta = data["meta"]
    lon0, lat0 = meta["origin"]
    districts = []
    for c in data["constituencies"]:
        rings = []
        for ring in c["path"].split("M"):
            numbers = [round(float(n)) for n in NUMBER.findall(ring)]
            if len(numbers) >= 6:
                rings.append(numbers)
        if not rings:
            print(f"{c['id']} has no outline", file=sys.stderr)
            return 1
        districts.append({"id": c["id"], "name": c["name"], "rings": rings})

    projection = {
        "west": lon0,
        "south": lat0,
        "scale": meta["unitsPerDegLat"],
        "cosLat": meta["unitsPerDegLon"] / meta["unitsPerDegLat"],
        "height": 0,
    }
    lines = [
        "// Generated by scripts/build_pulse_districts.py from templates/geo/nairobi-map.json",
        f"// ({meta['generated']}). Do not edit: re-run the script after the map is rebuilt.",
        "//",
        "// Nairobi's 17 constituencies as rings of map units, and the projection",
        "// from latitude and longitude into those units: x grows east, y grows",
        "// south, as in the SVG /map draws.",
        "",
        f"export const PROJECTION = {json.dumps(projection)};",
        "",
        "export const DISTRICTS = [",
    ]
    for d in districts:
        rings = ",".join("[" + ",".join(str(n) for n in ring) + "]" for ring in d["rings"])
        lines.append(f"\t{{ id: {json.dumps(d['id'])}, name: {json.dumps(d['name'])}, rings: [{rings}] }},")
    lines.append("];")
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {len(districts)} constituencies to {TARGET.relative_to(ROOT)} ({TARGET.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
